#!/bin/bash
# Build `expclaude` — an experimental copy of the claude CLI carrying the patches
# in experimental/, so a not-yet-trusted binary patch can be lived with for a
# while without touching the CLI you actually work in.
#
#   ./make-expclaude.sh          build (or rebuild) from the current live binary
#   ./make-expclaude.sh --list   show what would be applied, change nothing
#
# The copy starts from the LIVE binary, so it already carries everything
# patches/ applied this session; experimental/ goes on top. Rebuild after every
# claude update — the live binary is a fresh file each time and the copy does not
# follow it.
#
# Patches are aimed off the live binary by $CLAUDE_CLI_PATCH_TARGET, which
# _binpatch.candidate_binaries() honours ahead of every other resolution step
# (and refuses to fall back to the installed binary if the path is bogus).
set -euo pipefail

REPO="$(cd "$(dirname "$0")" && pwd)"
EXP_PATCHES="$REPO/experimental"
EXP_DIR="$HOME/.local/share/claude-exp"
WRAPPER="$HOME/.local/bin/expclaude"
CONFIG_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"

# CLAUDE_CLI_EXP_PATCHES_EXTRA_DIRS is the experimental twin of
# CLAUDE_CLI_PATCHES_EXTRA_DIRS (see run_cli_patches.sh): colon-separated extra
# directories, scanned after experimental/, relative entries resolved against
# $CLAUDE_CONFIG_DIR. Lets a private checkout carry experimental patches that
# can't live in this public repo.
EXP_DIRS=()
[ -d "$EXP_PATCHES" ] && EXP_DIRS+=("$EXP_PATCHES")
IFS=':' read -r -a _extra <<< "${CLAUDE_CLI_EXP_PATCHES_EXTRA_DIRS:-}"
for _d in ${_extra+"${_extra[@]}"}; do
    [ -n "$_d" ] || continue
    case "$_d" in
        /*)    ;;
        "~/"*) _d="$HOME/${_d#\~/}" ;;
        *)     _d="$CONFIG_DIR/$_d" ;;
    esac
    if [ -d "$_d" ]; then
        EXP_DIRS+=("$_d")
    else
        echo "CLAUDE_CLI_EXP_PATCHES_EXTRA_DIRS entry is not a directory: $_d" >&2
    fi
done

live="$(command -v claude || true)"
[ -n "$live" ] || { echo "no 'claude' on PATH" >&2; exit 1; }
live="$(readlink -f "$live")"
version="$(basename "$live")"
dest="$EXP_DIR/claude-$version-exp"

if [ "${1:-}" = "--list" ]; then
    echo "live binary : $live"
    echo "exp binary  : $dest"
    echo "wrapper     : $WRAPPER"
    echo "patches     : (in apply order)"
    for d in ${EXP_DIRS+"${EXP_DIRS[@]}"}; do
        for p in "$d"/*.py; do
            [ -f "$p" ] && printf '%s\t  - %s  (%s)\n' "$(basename "$p")" "$(basename "$p")" "$d"
        done
    done | LC_ALL=C sort -t"$(printf '\t')" -k1,1 -s | cut -f2-
    exit 0
fi

mkdir -p "$EXP_DIR" "$(dirname "$WRAPPER")"
# Start from pristine-live every time: an experimental patch that half-applied on
# a previous run must not compound onto itself.
rm -f "$dest" "$dest".orig "$dest".patch.* "$dest".patchold.*
cp "$live" "$dest"
chmod +x "$dest"
echo "copied $live -> $dest"

# Basename order across all dirs — zz-bytecode-off.py has to run last globally
# or the extra dirs' patches end up as dead text. Same reasoning as
# run_cli_patches.sh.
mapfile -t ORDERED < <(
    for d in ${EXP_DIRS+"${EXP_DIRS[@]}"}; do
        for p in "$d"/*.py; do
            [ -f "$p" ] && printf '%s\t%s\n' "$(basename "$p")" "$p"
        done
    done | LC_ALL=C sort -t"$(printf '\t')" -k1,1 -s | cut -f2-
)

failed=0
for p in ${ORDERED+"${ORDERED[@]}"}; do
    name="$(basename "$p")"
    if CLAUDE_CLI_PATCH_TARGET="$dest" python3 "$p"; then
        echo "  applied $name"
    else
        echo "  FAILED  $name (see message above)" >&2
        failed=1
    fi
done

if [ "$failed" -ne 0 ]; then
    echo "at least one experimental patch failed — removing $dest so you don't run a half-patched CLI" >&2
    rm -f "$dest" "$dest".orig
    exit 1
fi

cat > "$WRAPPER" <<EOF
#!/bin/bash
# Generated by $REPO/make-expclaude.sh — do not edit; rebuild instead.
# Experimental claude CLI: live binary + $REPO/experimental/*.
# Autoupdate is off so this copy can never be swapped out from under you.
exec env DISABLE_AUTOUPDATER=1 "$dest" "\$@"
EOF
chmod +x "$WRAPPER"

echo "wrote $WRAPPER -> $dest"
"$dest" --version || true
